"""The skills are the guide's brain and ship in two places (Claude Code and GitHub Copilot).
These tests keep them valid, identical, and discoverable."""

import re
from pathlib import Path

import pytest
import sync_skills as sync

ROOT = Path(__file__).resolve().parent.parent
CLAUDE = ROOT / ".claude" / "skills"
COPILOT = ROOT / ".github" / "skills"
EXPECTED = {
    "kit-guide", "setup-my-computer", "connect-the-kit", "upload-and-debug", "make-magic",
    "kit-hardware", "kit-mentor", "restore-flappy", "share-my-project", "improve-this-guide",
}  # fmt: skip


def test_every_capability_has_a_skill():
    assert {p.name for p in CLAUDE.iterdir() if p.is_dir()} == EXPECTED


@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_skill_frontmatter_is_valid_for_both_tools(name):
    meta = sync.parse_frontmatter((CLAUDE / name / "SKILL.md").read_text(encoding="utf-8"))
    assert meta["name"] == name
    assert re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) and len(name) <= 64
    assert 40 <= len(meta["description"]) <= 1024  # Copilot's limit
    assert "TRIGGER:" in meta["description"], "a skill nobody can trigger is dead weight"


@pytest.mark.parametrize("name", sorted(EXPECTED - {"improve-this-guide"}))
def test_learner_skills_trigger_in_hebrew_too(name):
    """Hebrew is the default language: a Hebrew-speaking child must reach every learner skill in Hebrew."""
    description = sync.parse_frontmatter((CLAUDE / name / "SKILL.md").read_text(encoding="utf-8"))["description"]
    triggers = description.partition("TRIGGER:")[2]
    assert re.search(r"[֐-׿]", triggers), f"{name} has no Hebrew trigger phrase"


def test_the_copilot_copy_is_identical_to_the_claude_source():
    assert sync.drift() == [], "run: python scripts/sync_skills.py"


def test_a_skill_edit_that_is_not_synced_is_caught():
    """A guard that cannot be tripped is worthless: prove the drift check notices."""
    skill = CLAUDE / "kit-mentor" / "SKILL.md"
    original = skill.read_bytes()
    try:
        skill.write_bytes(original + b"\nan unsynced edit\n")
        assert any("kit-mentor" in problem for problem in sync.drift())
    finally:
        skill.write_bytes(original)
    assert sync.drift() == []


def test_crlf_line_endings_are_not_reported_as_drift():
    copy = COPILOT / "kit-mentor" / "SKILL.md"
    original = copy.read_bytes()
    try:
        copy.write_bytes(original.replace(b"\n", b"\r\n"))
        assert sync.drift() == []
    finally:
        copy.write_bytes(original)


def test_instructions_files_index_every_skill():
    for target in sync.INSTRUCTION_FILES:
        text = target.read_text(encoding="utf-8")
        assert "GENERATED by scripts/sync_skills.py" in text
        for name in EXPECTED:
            assert f"`{name}`" in text, (target.name, name)
            assert f".github/skills/{name}/SKILL.md" in text


def test_the_github_copy_links_work_from_inside_dot_github():
    inside = (ROOT / ".github" / "copilot-instructions.md").read_text(encoding="utf-8")
    at_root = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    assert "](../docs/" in inside and "](docs/" not in inside
    assert "](docs/" in at_root and "](../docs/" not in at_root


def test_kit_guide_hands_over_to_every_other_skill():
    text = (CLAUDE / "kit-guide" / "SKILL.md").read_text(encoding="utf-8")
    for name in EXPECTED - {"kit-guide"}:
        assert f"`{name}`" in text, f"kit-guide never mentions {name}"


def test_claude_md_routes_to_every_skill_and_keeps_the_standing_rules():
    text = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    for name in EXPECTED:
        assert f"`{name}`" in text, f"CLAUDE.md never routes to {name}"
    for rule in ("check_updates.py", "Hebrew", "env/", "my_projects/", "listen.py", "3V3"):
        assert rule in text, rule


def test_last_updated_mark_is_stamped_in_both_languages():
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    mark = html.split("<!-- last-updated:start -->")[1].split("<!-- last-updated:end -->")[0]
    assert "Last updated" in mark and "עודכן לאחרונה" in mark
